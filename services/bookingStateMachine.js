/**
 * PARVA PLATFORM — AUTHORITATIVE 16-STATE BOOKING STATE MACHINE
 * Version 2.0.0
 */

export const BOOKING_STATES = {
  DRAFT: 'DRAFT',
  PRICE_CONFIRMED: 'PRICE_CONFIRMED',
  SLOT_HELD: 'SLOT_HELD',
  PAYMENT_PENDING: 'PAYMENT_PENDING',
  PAYMENT_SUCCESS: 'PAYMENT_SUCCESS',
  VENDOR_PENDING: 'VENDOR_PENDING',
  VENDOR_ACCEPTED: 'VENDOR_ACCEPTED',
  CONFIRMED: 'CONFIRMED',
  EVENT_STARTED: 'EVENT_STARTED',
  COMPLETED: 'COMPLETED',
  CANCELLED: 'CANCELLED',
  REJECTED: 'REJECTED',
  REFUND_PENDING: 'REFUND_PENDING',
  REFUNDED: 'REFUNDED',
  PAYMENT_FAILED: 'PAYMENT_FAILED',
  EXPIRED: 'EXPIRED'
};

const ALLOWED_TRANSITIONS = {
  [BOOKING_STATES.DRAFT]: [BOOKING_STATES.PRICE_CONFIRMED, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.PRICE_CONFIRMED]: [BOOKING_STATES.SLOT_HELD, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.SLOT_HELD]: [BOOKING_STATES.PAYMENT_PENDING, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.PAYMENT_PENDING]: [BOOKING_STATES.PAYMENT_SUCCESS, BOOKING_STATES.PAYMENT_FAILED, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.PAYMENT_SUCCESS]: [BOOKING_STATES.VENDOR_PENDING, BOOKING_STATES.CONFIRMED],
  [BOOKING_STATES.VENDOR_PENDING]: [BOOKING_STATES.VENDOR_ACCEPTED, BOOKING_STATES.VENDOR_REJECTED, BOOKING_STATES.CANCELLED],
  [BOOKING_STATES.VENDOR_ACCEPTED]: [BOOKING_STATES.CONFIRMED, BOOKING_STATES.CANCELLED],
  [BOOKING_STATES.CONFIRMED]: [BOOKING_STATES.EVENT_STARTED, BOOKING_STATES.CANCELLED],
  [BOOKING_STATES.EVENT_STARTED]: [BOOKING_STATES.COMPLETED],
  [BOOKING_STATES.VENDOR_REJECTED]: [BOOKING_STATES.REFUND_PENDING],
  [BOOKING_STATES.CANCELLED]: [BOOKING_STATES.REFUND_PENDING, BOOKING_STATES.COMPLETED],
  [BOOKING_STATES.REFUND_PENDING]: [BOOKING_STATES.REFUNDED],
  [BOOKING_STATES.COMPLETED]: [],
  [BOOKING_STATES.REFUNDED]: [],
  [BOOKING_STATES.PAYMENT_FAILED]: [BOOKING_STATES.PAYMENT_PENDING, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.EXPIRED]: []
};

/**
 * Validates state transition
 */
export function validateBookingTransition(currentStatus, nextStatus) {
  if (!BOOKING_STATES[nextStatus]) {
    throw new Error(`INVALID_STATE: Target state "${nextStatus}" is not a recognized PARVA booking state.`);
  }
  const allowed = ALLOWED_TRANSITIONS[currentStatus] || [];
  if (!allowed.includes(nextStatus)) {
    throw new Error(`INVALID_STATE_TRANSITION: Cannot transition booking from "${currentStatus}" to "${nextStatus}". Allowed: [${allowed.join(', ')}]`);
  }
  return true;
}

/**
 * Idempotency registry for network duplicate prevention
 */
const idempotencyRegistry = new Map();

export function checkIdempotency(key) {
  if (!key) return null;
  const record = idempotencyRegistry.get(key);
  if (record && Date.now() - record.createdAt < 24 * 60 * 60 * 1000) {
    return record.response;
  }
  return null;
}

export function saveIdempotency(key, response) {
  if (!key) return;
  idempotencyRegistry.set(key, { response, createdAt: Date.now() });
}
